#   cm_push_pop_all.S
#
#   cm.push and cm.pop for every register list (rlist 4 to 15) and every stack
#   adjustment (spimm 0 to 3), on RV32.
#
#   For each case the test:
#     1. gives each saved register a distinct value,
#     2. runs cm.push and checks the new sp and every stored 32-bit word: the
#        registers are stored from the highest-numbered one down, so the last
#        s register of the list is at sp_old-4 and ra at the lowest address,
#     3. overwrites the saved registers,
#     4. runs cm.pop and checks that every register is restored and that sp is
#        back to its value before cm.push.
#   The stack is filled with a marker before each case, so a store to the wrong
#   slot or a missing store is caught.
#
#   Failure writes the case number to tohost as (2*n+1) with n >= 1; a0..a5 and
#   t0..t6 are scratch.
#
#   Generated by gen/gen_zcmp_all.py: edit the generator, not this file.
# ------------------------------------------------------------------------------

