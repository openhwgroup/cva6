# s registers of an rlist, in list order (ra first)
S_REGS = ["s0", "s1", "s2", "s3", "s4", "s5", "s6", "s7", "s8", "s9", "s10", "s11"]


def rlist_regs(rlist):
    """Registers of rlist 4..15, ra first, then s0..; rlist 15 holds s0-s11."""
    n_s = rlist - 4 if rlist < 15 else 12
    return ["ra"] + S_REGS[:n_s]


def reg_list_text(regs):
    if len(regs) == 1:
        return "{ra}"
    if len(regs) == 2:
        return "{ra, s0}"
    return "{ra, s0-%s}" % regs[-1]


def stack_adj(rlist, spimm, xlen):
    nbytes = len(rlist_regs(rlist)) * xlen // 8
    base = (nbytes + 15) // 16 * 16
    return base + 16 * spimm


def cfg(xlen):
    if xlen == 32:
        return dict(env="RVTEST_RV32U", sx="sw", lx="lw", b=4,
                    mark="0xDEADBEEF", val=lambda c, k: "0x%08x" % ((c << 12) | k))
    return dict(env="RVTEST_RV64U", sx="sd", lx="ld", b=8,
                mark="0xDEADBEEFCAFEF00D",
                val=lambda c, k: "0x%08x%08x" % (0xA5000000 | c, (c << 12) | k))


def gen_push_pop(xlen):
    c = cfg(xlen)
    out = []
    case = 0
    for rlist in range(4, 16):
        regs = rlist_regs(rlist)
        for spimm in range(4):
            case += 1
            adj = stack_adj(rlist, spimm, xlen)
            out.append(f"""
    # ----- case {case}: rlist {rlist} {reg_list_text(regs)}, spimm {spimm}, stack adjustment {adj}
    li    gp, {case}
    la    sp, stack_top
    la    t0, stack_bot
    li    t1, MARK
1:  {c['sx']}    t1, 0(t0)
    addi  t0, t0, {c['b']}
    bltu  t0, sp, 1b
""")
            for k, r in enumerate(regs, 1):
                out.append(f"    li    {r}, {c['val'](case, k)}\n")
            out.append(f"""    mv    a0, sp                # sp before push
    cm.push {reg_list_text(regs)}, -{adj}
    addi  a1, a0, -{adj}
    bne   sp, a1, fail
""")
            # stored from sp-b downwards in the order s11..s0, ra
            for slot, k in enumerate(range(len(regs), 0, -1), 1):
                out.append(f"""    {c['lx']}    t2, -{slot * c['b']}(a0)
    li    t3, {c['val'](case, k)}
    bne   t2, t3, fail
""")
            # the slot below the list is untouched, when it is inside the frame
            if (len(regs) + 1) * c['b'] <= adj:
                out.append(f"""    {c['lx']}    t2, -{(len(regs) + 1) * c['b']}(a0)
    li    t3, MARK
    bne   t2, t3, fail
""")
            for r in regs[1:] + ["ra"]:
                out.append(f"    li    {r}, 0\n")
            out.append(f"""    cm.pop  {reg_list_text(regs)}, {adj}
    bne   sp, a0, fail
""")
            for k, r in enumerate(regs, 1):
                out.append(f"""    li    t3, {c['val'](case, k)}
    bne   {r}, t3, fail
""")
    desc = f"""#   cm.push and cm.pop for every register list (rlist 4 to 15) and every stack
#   adjustment (spimm 0 to 3), on RV{xlen}.
#
#   For each case the test:
#     1. gives each saved register a distinct value,
#     2. runs cm.push and checks the new sp and every stored {xlen}-bit word: the
#        registers are stored from the highest-numbered one down, so the last
#        s register of the list is at sp_old-{c['b']} and ra at the lowest address,
#     3. overwrites the saved registers,
#     4. runs cm.pop and checks that every register is restored and that sp is
#        back to its value before cm.push.
#   The stack is filled with a marker before each case, so a store to the wrong
#   slot or a missing store is caught.
#
#   Failure writes the case number to tohost as (2*n+1) with n >= 1; a0..a5 and
#   t0..t6 are scratch."""
    return desc, f"""
#define MARK {c['mark']}

{c['env']}
RVTEST_CODE_BEGIN
    li    gp, 0                 # case counter, reported on failure

""" + "".join(out) + """
pass:
    RVTEST_PASS

fail:
    RVTEST_FAIL
""" + TRAILER_STACK


def gen_popret(xlen):
    c = cfg(xlen)
    calls = []
    fns = []
    case = 0
    for rlist in range(4, 16):
        regs = rlist_regs(rlist)
        for spimm in range(4):
            adj = stack_adj(rlist, spimm, xlen)
            for op in ("cm.popret", "cm.popretz"):
                case += 1
                marker = "0x%x077" % case
                calls.append(f"""    # case {case}: {op} {reg_list_text(regs)}, {adj}
    li    gp, {case}
    la    sp, stack_top
""")
                for k, r in enumerate(regs[1:], 2):
                    calls.append(f"    li    {r}, {'0x%x%03x' % (case, k)}\n")
                calls.append(f"""    li    a0, 0
    mv    a2, sp
    jal   fn_{case}
ret_{case}:
    bne   sp, a2, fail
""")
                for k, r in enumerate(regs[1:], 2):
                    calls.append(f"""    li    t1, {'0x%x%03x' % (case, k)}
    bne   {r}, t1, fail
""")
                if op == "cm.popret":
                    calls.append(f"""    li    t1, {marker}
    bne   a0, t1, fail
""")
                else:
                    calls.append("    bnez  a0, fail\n")
                calls.append(f"""    la    t1, ret_{case}
    bne   ra, t1, fail
""")
                fns.append(f"\nfn_{case}:\n    cm.push {reg_list_text(regs)}, -{adj}\n")
                for r in regs[1:]:
                    fns.append(f"    li    {r}, -1\n")
                fns.append(f"""    li    a0, {marker}
    la    ra, fail              # must be reloaded from the stack
    {op} {reg_list_text(regs)}, {adj}
    j     fail                  # {op} must not fall through
""")
    desc = f"""#   cm.popret and cm.popretz for every register list (rlist 4 to 15) and every
#   stack adjustment (spimm 0 to 3), as the epilogue of a called function, on
#   RV{xlen}:
#     - the caller calls fn_N, which runs cm.push, overwrites the saved
#       registers and ra, sets a0 to a marker, then returns with cm.popret or
#       cm.popretz;
#     - back in the caller, the test checks that it came back to the right
#       place (ra reloaded from the stack, not the overwritten value), that
#       every saved register holds its value from before the call, that sp is
#       unchanged, and that a0 is zero after cm.popretz and still the marker
#       after cm.popret.
#
#   Failure writes the case number to tohost as (2*n+1)."""
    return desc, f"""
{c['env']}
RVTEST_CODE_BEGIN
    li    gp, 0

""" + "".join(calls) + """
pass:
    RVTEST_PASS

fail:
    RVTEST_FAIL
""" + "".join(fns) + TRAILER_STACK


def gen_mv(xlen):
    c = cfg(xlen)
    sregs = ["s0", "s1", "s2", "s3", "s4", "s5", "s6", "s7"]
    out = []
    case = 0
    hi = (lambda v: v) if xlen == 32 else (lambda v: v | (0x5A << 40))
    for r1 in sregs:
        for r2 in sregs:
            case += 1
            v1, v2 = hi((case << 8) | 1), hi((case << 8) | 2)
            if r1 == r2:
                v2 = v1
            out.append(f"""    # case {case}: cm.mva01s {r1}, {r2}
    li    gp, {case}
    li    {r1}, {hex(v1)}
""")
            if r1 != r2:
                out.append(f"    li    {r2}, {hex(v2)}\n")
            out.append(f"""    li    a0, 0
    li    a1, 0
    cm.mva01s {r1}, {r2}
    add   t0, a0, a1
    li    t1, {hex(v1)}
    bne   a0, t1, fail
    li    t1, {hex(v2)}
    bne   a1, t1, fail
    li    t1, {hex((v1 + v2) & ((1 << xlen) - 1))}
    bne   t0, t1, fail
""")
    for i, r1 in enumerate(sregs):
        for j, r2 in enumerate(sregs):
            if r1 == r2:
                continue
            case += 1
            v1, v2 = hi(0x4000 | ((case - 64) << 8) | 1), hi(0x4000 | ((case - 64) << 8) | 2)
            out.append(f"""    # case {case}: cm.mvsa01 {r1}, {r2}
    li    gp, {case}
    li    a0, {hex(v1)}
    li    a1, {hex(v2)}
    li    {r1}, 0
    li    {r2}, 0
    cm.mvsa01 {r1}, {r2}
    add   t0, {r1}, {r2}
    li    t1, {hex(v1)}
    bne   {r1}, t1, fail
    li    t1, {hex(v2)}
    bne   {r2}, t1, fail
    li    t1, {hex((v1 + v2) & ((1 << xlen) - 1))}
    bne   t0, t1, fail
""")
    desc = f"""#   cm.mva01s and cm.mvsa01 for every pair of the eight s registers they can
#   name (s0, s1, s2 to s7), on RV{xlen}:
#     - cm.mva01s r1s, r2s copies r1s to a0 and r2s to a1, for all 64 pairs,
#       including r1s == r2s, which is legal;
#     - cm.mvsa01 r1s, r2s copies a0 to r1s and a1 to r2s, for the 56 pairs
#       with r1s != r2s (r1s == r2s is reserved).
#   Each copy is followed at once by an instruction that reads the result, so
#   the two micro-ops of the move and their consumer go through the issue stage
#   back to back.
#
#   Failure writes the case number to tohost as (2*n+1)."""
    return desc, f"""
{c['env']}
RVTEST_CODE_BEGIN
    li    gp, 0

""" + "".join(out) + """
pass:
    RVTEST_PASS

fail:
    RVTEST_FAIL

RVTEST_CODE_END

    .data
RVTEST_DATA_BEGIN
RVTEST_DATA_END
"""


def main():
    outdir = sys.argv[1]
    for base, fn in (("cm_push_pop_all", gen_push_pop), ("cm_popret_all", gen_popret),
                     ("cm_mv_all", gen_mv)):
        for xlen in (32, 64):
            name = f"{base}.S" if xlen == 32 else f"{base}_rv64.S"
            desc, body = fn(xlen)
            with open(os.path.join(outdir, name), "w") as f:
                f.write(HEADER.format(name=name, desc=desc) + body)


if __name__ == "__main__":
    main()
